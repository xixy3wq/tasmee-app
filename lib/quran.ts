export const SSTART: number[] = [];
export let TOTAL = 0;
AYAS.forEach((n, i) => { SSTART[i] = TOTAL; TOTAL += n; });
export const gOf = (surah: number, ayah: number) => SSTART[surah - 1] + ayah - 1;
function build(dir: "fwd" | "bwd") {
  const ord: number[] = [];
  const ss = [...Array(114).keys()];
  if (dir === "bwd") ss.reverse();
  ss.forEach((s) => { for (let a = 0; a < AYAS[s]; a++) ord.push(SSTART[s] + a); });
  const pos: number[] = new Array(TOTAL);
  ord.forEach((g, i) => (pos[g] = i));
  return { ord, pos };
}
export const ORD = { fwd: build("fwd"), bwd: build("bwd") };
export const validRange = (surah: number, from: number, to: number) =>
  surah >= 1 && surah <= 114 && from >= 1 && to >= from && to <= AYAS[surah - 1];
